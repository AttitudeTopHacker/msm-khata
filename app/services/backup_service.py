import json
import csv
import io
from datetime import datetime, timezone
from typing import Dict, Any, Optional
import requests
from app.database import get_supabase
from app.services.ledger_service import LedgerService

class BackupService:
    @staticmethod
    def generate_full_backup(user_id: Optional[str] = None) -> Dict[str, Any]:
        """
        Generates a complete snapshot of all Ledger data:
        Profiles, Persons, Categories, Transactions, and Saved Filters.
        """
        client = get_supabase()
        
        # 1. Fetch Persons
        p_query = client.table("persons").select("*")
        if user_id:
            p_query = p_query.eq("user_id", user_id)
        persons = p_query.execute().data or []
        
        # 2. Fetch Categories
        c_query = client.table("categories").select("*")
        if user_id:
            c_query = c_query.eq("user_id", user_id)
        categories = c_query.execute().data or []
        
        # 3. Fetch Transactions
        t_query = client.table("transactions").select(
            "*, persons(name), categories(name, color)"
        ).order("transaction_date", desc=False)
        if user_id:
            t_query = t_query.eq("user_id", user_id)
        transactions = t_query.execute().data or []
        
        # 4. Fetch Saved Filters
        f_query = client.table("saved_filters").select("*")
        if user_id:
            f_query = f_query.eq("user_id", user_id)
        saved_filters = f_query.execute().data or []
        
        # 5. Calculate summary snapshot
        dashboard = LedgerService.calculate_dashboard_summary(user_id)
        
        now_str = datetime.now(timezone.utc).isoformat()
        
        return {
            "metadata": {
                "app": "MsmKhata",
                "organization": "msm.movin",
                "version": "1.0.0",
                "exported_at": now_str,
                "user_id": user_id,
            },
            "summary_at_export": {
                "total_receivable": dashboard.total_receivable,
                "total_payable": dashboard.total_payable,
                "net_position": dashboard.net_len_den_position,
                "total_transactions": len(transactions),
            },
            "persons": persons,
            "categories": categories,
            "transactions": transactions,
            "saved_filters": saved_filters,
        }

    @staticmethod
    def generate_csv_export(user_id: Optional[str] = None) -> str:
        """
        Generates standard CSV spreadsheet of all transactions
        for Microsoft Excel / Google Sheets compatibility.
        """
        backup = BackupService.generate_full_backup(user_id)
        transactions = backup.get("transactions", [])
        
        output = io.StringIO()
        writer = csv.writer(output)
        
        # Header row
        writer.writerow([
            "Transaction ID",
            "Date",
            "Type",
            "Amount (INR)",
            "Person / Contact",
            "Category",
            "Payment Mode",
            "Status",
            "Due Date",
            "Remarks / Notes"
        ])
        
        for t in transactions:
            person_info = t.get("persons") or {}
            cat_info = t.get("categories") or {}
            
            type_label = {
                "GIVEN": "Maine Diye (Udhar Diya)",
                "TAKEN": "Maine Liye (Udhar Liya)",
                "EXPENSE": "Kharcha",
                "INCOME": "Kamai"
            }.get(t.get("type"), t.get("type"))
            
            writer.writerow([
                t.get("id"),
                t.get("transaction_date", ""),
                type_label,
                t.get("amount", 0.0),
                person_info.get("name", ""),
                cat_info.get("name", ""),
                t.get("payment_mode", "CASH"),
                "Settled" if t.get("is_settled") else "Pending",
                t.get("due_date", ""),
                t.get("notes", "")
            ])
            
        return output.getvalue()

    @staticmethod
    def upload_to_google_drive(
        access_token: str,
        backup_content: str,
        filename: str,
        mime_type: str = "application/json"
    ) -> Dict[str, Any]:
        """
        Directly uploads the backup to user's Google Drive via
        Google Drive REST API v3 multipart upload.
        """
        metadata = {
            "name": filename,
            "description": "Automated backup generated by MsmKhata (msm.movin)",
            "mimeType": mime_type
        }
        
        # 1. Check or create "MsmKhata Backups" folder
        headers = {"Authorization": f"Bearer {access_token}"}
        folder_query = "name = 'MsmKhata Backups' and mimeType = 'application/vnd.google-apps.folder' and trashed = false"
        search_res = requests.get(
            f"https://www.googleapis.com/drive/v3/files?q={folder_query}",
            headers=headers
        )
        
        folder_id = None
        if search_res.status_code == 200:
            files = search_res.json().get("files", [])
            if files:
                folder_id = files[0]["id"]
                
        if not folder_id:
            # Create folder
            folder_payload = {
                "name": "MsmKhata Backups",
                "mimeType": "application/vnd.google-apps.folder"
            }
            folder_res = requests.post(
                "https://www.googleapis.com/drive/v3/files",
                headers=headers,
                json=folder_payload
            )
            if folder_res.status_code in [200, 201]:
                folder_id = folder_res.json().get("id")
                
        if folder_id:
            metadata["parents"] = [folder_id]
            
        # 2. Upload file via multipart request
        files = {
            "data": ("metadata", json.dumps(metadata), "application/json; charset=UTF-8"),
            "file": (filename, backup_content, mime_type)
        }
        
        upload_res = requests.post(
            "https://www.googleapis.com/upload/drive/v3/files?uploadType=multipart",
            headers={"Authorization": f"Bearer {access_token}"},
            files=files
        )
        
        if upload_res.status_code not in [200, 201]:
            raise RuntimeError(f"Google Drive upload failed: {upload_res.text}")
            
        return upload_res.json()
