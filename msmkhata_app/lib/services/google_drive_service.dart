import 'dart:convert';
import 'dart:typed_data';
import 'package:flutter/foundation.dart';
import 'package:http/http.dart' as http;

/// Direct Google Drive REST API v3 Service
/// Uploads statement PDFs directly into user's "MsmKhata Backups" folder.
class GoogleDriveDirectService {
  static const String _driveFilesEndpoint = 'https://www.googleapis.com/drive/v3/files';
  static const String _uploadEndpoint = 'https://www.googleapis.com/upload/drive/v3/files?uploadType=multipart';

  /// Checks whether Google Drive access token is valid and active.
  static Future<bool> validateToken(String accessToken) async {
    final clean = accessToken.trim();
    if (clean.isEmpty || clean.startsWith('eyJ')) {
      return false;
    }
    try {
      final res = await http.get(
        Uri.parse('$_driveFilesEndpoint?pageSize=1&fields=files(id)'),
        headers: {'Authorization': 'Bearer $clean'},
      );
      return res.statusCode == 200;
    } catch (_) {
      return false;
    }
  }

  /// Ensures the "MsmKhata Backups" folder exists in user's Google Drive and returns its ID.
  static Future<String?> getOrCreateBackupFolder(String accessToken) async {
    final headers = {'Authorization': 'Bearer $accessToken'};

    try {
      final q = Uri.encodeComponent("name = 'MsmKhata Backups' and mimeType = 'application/vnd.google-apps.folder' and trashed = false");
      final searchRes = await http.get(
        Uri.parse('$_driveFilesEndpoint?q=$q&spaces=drive&fields=files(id,name)'),
        headers: headers,
      );

      if (searchRes.statusCode == 200) {
        final data = jsonDecode(searchRes.body) as Map<String, dynamic>;
        final files = data['files'] as List<dynamic>?;
        if (files != null && files.isNotEmpty) {
          return files[0]['id'] as String?;
        }
      }

      // If folder not found, create "MsmKhata Backups"
      final createRes = await http.post(
        Uri.parse(_driveFilesEndpoint),
        headers: {
          ...headers,
          'Content-Type': 'application/json',
        },
        body: jsonEncode({
          'name': 'MsmKhata Backups',
          'mimeType': 'application/vnd.google-apps.folder',
        }),
      );

      if (createRes.statusCode == 200 || createRes.statusCode == 201) {
        final created = jsonDecode(createRes.body) as Map<String, dynamic>;
        return created['id'] as String?;
      }
    } catch (e) {
      debugPrint('Folder check/creation notice: $e');
    }
    return null;
  }

  /// Uploads arbitrary PDF / document bytes directly into Google Drive.
  static Future<Map<String, dynamic>> uploadPdfBytes({
    required String accessToken,
    required Uint8List bytes,
    required String fileName,
    String? folderId,
  }) async {
    final targetFolderId = folderId ?? await getOrCreateBackupFolder(accessToken);
    final boundary = '----MsmKhataMultipart${DateTime.now().millisecondsSinceEpoch}';

    final metadata = {
      'name': fileName,
      'description': 'Automated ledger backup generated by MsmKhata (msm.movin)',
      'mimeType': 'application/pdf',
      if (targetFolderId != null) 'parents': [targetFolderId],
    };

    final metadataPart = '--$boundary\r\nContent-Type: application/json; charset=UTF-8\r\n\r\n${jsonEncode(metadata)}\r\n';
    final mediaHeaderPart = '--$boundary\r\nContent-Type: application/pdf\r\n\r\n';
    final footerPart = '\r\n--$boundary--\r\n';

    final metadataBytes = utf8.encode(metadataPart);
    final mediaHeaderBytes = utf8.encode(mediaHeaderPart);
    final footerBytes = utf8.encode(footerPart);

    final payload = Uint8List.fromList([
      ...metadataBytes,
      ...mediaHeaderBytes,
      ...bytes,
      ...footerBytes,
    ]);

    final res = await http.post(
      Uri.parse(_uploadEndpoint),
      headers: {
        'Authorization': 'Bearer $accessToken',
        'Content-Type': 'multipart/related; boundary=$boundary',
        'Content-Length': payload.length.toString(),
      },
      body: payload,
    );

    if (res.statusCode == 200 || res.statusCode == 201) {
      return Map<String, dynamic>.from(jsonDecode(res.body));
    }

    if (res.statusCode == 401) {
      throw Exception('ACCESS_TOKEN_EXPIRED (401): Google Drive session expired. Please re-authorize Google Drive.');
    }

    if (res.statusCode == 403) {
      throw Exception('ACCESS_TOKEN_SCOPE_INSUFFICIENT (403): Google Drive permission denied. Please re-authorize Google Drive.');
    }

    throw Exception('Failed to upload "$fileName" to Google Drive (${res.statusCode}): ${res.body}');
  }
}

